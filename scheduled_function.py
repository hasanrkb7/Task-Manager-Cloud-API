import functions_framework
from datetime import datetime
import json

@functions_framework.cloud_event
def scheduled_task_report(cloud_event):
    """
    This function runs on a schedule (every 5 minutes).
    It generates a report about task activity.
    This demonstrates a time-triggered cloud function (event-driven, not API-triggered).
    """
    
    # Get current timestamp
    current_time = datetime.utcnow()
    
    # Create a simple report
    report = {
        "report_time": current_time.isoformat(),
        "report_type": "scheduled_task_summary",
        "message": "This is an automated report generated by a scheduled Cloud Function",
        "trigger": "Cloud Scheduler (cron job)",
        "next_run": "In 5 minutes"
    }
    
    # Log the report (viewable in Cloud Logging)
    print(f"SCHEDULED REPORT: {json.dumps(report, indent=2)}")
    
    return json.dumps({"status": "report_generated", "timestamp": current_time.isoformat()})